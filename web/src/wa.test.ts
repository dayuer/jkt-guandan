import { describe, expect, it } from "vitest";
import { maskWaPhone, normalizeWaPhone } from "./wa";

describe("normalizeWaPhone", () => {
  it.each([
    ["0812-3456-7890", "+6281234567890"],
    ["0812 3456 7890", "+6281234567890"],
    ["62 812 3456 7890", "+6281234567890"],
    ["+62 812-3456-7890", "+6281234567890"],
    ["812 3456 7890", "+6281234567890"],
    ["812345678", "+62812345678"],
    ["86 138 1234 5678", "+8613812345678"],
    ["8613812345678", "+8613812345678"],
    ["+86 138 1234 5678", "+8613812345678"],
    ["6281234567890", "+6281234567890"],
    ["0065 9123 4567", "+6591234567"],
    ["+86 138 0013 8000", "+8613800138000"],
  ])("%s → %s", (input, want) => {
    expect(normalizeWaPhone(input)).toBe(want);
  });

  it.each([
    "",
    "abc",
    "12",
    "+0123456789",
    "+62812345678901234567",
    // 86 开头但不是 13 位：可能是 +86，也可能是印尼号，不猜。
    "861381234567",
    "86138123456789",
    // 8 开头但位数不像印尼手机号。
    "81234567",
    "8123456789012",
    // 62 开头但后面不是印尼手机号。
    "62212345678",
    // 夹了字母。
    "0812abc7890",
  ])("认不出来或有歧义：%s", (input) => {
    expect(normalizeWaPhone(input)).toBeNull();
  });
});

describe("maskWaPhone", () => {
  it("印尼号码按设计稿写法脱敏", () => {
    expect(maskWaPhone("+6281234567890")).toBe("+62 812****890");
  });
  it("其他国家只露头尾", () => {
    expect(maskWaPhone("+8613800138000")).toBe("+861****000");
  });
});
